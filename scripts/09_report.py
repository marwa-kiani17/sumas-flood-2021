"""Step 9: build reports/results.md from the saved tables (so numbers always match the outputs).

Run:  python scripts/09_report.py      (after steps 3-8)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import pandas as pd
import yaml

CFG = yaml.safe_load(open(ROOT / "config.yaml"))
PROC, REP = ROOT / CFG["paths"]["processed"], ROOT / "reports"


def md(df, floatfmt=3):
    """DataFrame -> GitHub markdown table."""
    df = df.copy()
    cols = [str(c) for c in df.columns]
    rows = []
    for _, r in df.iterrows():
        rows.append("| " + " | ".join(f"{v:.{floatfmt}f}" if isinstance(v, float) and pd.notna(v) else
                                       ("" if pd.isna(v) else str(v)) for v in r) + " |")
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + rows)


def read(name, **kw):
    p = REP / name if (REP / name).exists() else PROC / name
    return pd.read_csv(p, **kw) if p.exists() else None


out = ["# Results\n", "_Generated by `scripts/09_report.py` from the saved tables. Test years: 2017-2023 (never used for training)._\n"]

# ---- Part C: forecasting ----
skill = read("tables_skill_per_river.csv", dtype={"station": str})
if skill is not None:
    n = skill["station"].nunique()
    med = skill.drop(columns="station").groupby("lead").median().reset_index()
    out += [f"## Part C: river forecasting ({n} rivers, median over rivers)\n",
            "NSE / KGE: 1 = perfect. `lgbm` = LightGBM median model with perfect-forecast future weather.\n",
            md(med), ""]

warn = read("tables_warning.csv")
if warn is not None:
    out += ["### Flood warning (rule: 0.9 quantile forecast > 5-year flood Q5) and 10-90% coverage\n",
            "POD = share of real exceedances warned; FAR = share of warnings that were false; CSI = combined (higher is better). "
            "Coverage of the 10-90% range should be about 0.80.\n", md(warn), ""]

pe = read("tables_peak_errors.csv")
if pe is not None:
    if "variant" not in pe:
        pe["variant"] = "full"
    g = pe.groupby(["variant", "lead"]).agg(events=("peak_err_pct", "size"),
                                            median_abs_peak_error_pct=("peak_err_pct", lambda s: s.abs().median()),
                                            median_signed_peak_error_pct=("peak_err_pct", "median"),
                                            median_abs_timing_days=("timing_err_days", lambda s: s.abs().median())).reset_index()
    out += ["### Peak size and timing error for floods above Q2 (median model; negative = under-predicted)\n", md(g, 2), ""]

reg = read("tables_warning_by_regime.csv")
if reg is not None:
    out += ["### Warning scores by river regime (rule: 0.9 quantile > Q5), model vs persistence\n",
            "Pooled scores are dominated by slow snowmelt floods, where 'tomorrow = today' works well. Rain-driven "
            "rivers (the Nov 2021 type) have few flood days in the test years, so read those rows as indicative.\n",
            md(reg, 2), ""]

nov = read("tables_nov2021_warning.csv", dtype={"river": str})
if nov is not None:
    out += ["### November 2021 replay: first day the warning fired (issue date)\n",
            "`days_gained` = persistence warning day minus model warning day. 'no_future' uses no future weather. "
            "Empty = no warning fired.\n", md(nov.drop(columns=["Q5"], errors="ignore"), 1), ""]

# ---- Part B: hydraulics ----
thr = read("thresholds.csv", dtype={"id": str})
if thr is not None:
    t = thr[["id", "name", "n_train_years", "Q2", "Q5", "Q10", "Q25", "nov2021_peak", "nov2021_return_period"]].copy()
    t["nov2021_return_period"] = t["nov2021_return_period"].map(lambda v: ">100" if v > 100 else f"{v:.0f}")
    out += ["## Part B: flood frequency (GEV fitted to 1981-2012 annual maxima, m3/s)\n",
            "GEV shape bounded to [-0.1, 0.4]. Return periods above 100 years come from a 21-32 year fit and are "
            "only indicative.\n", md(t, 1), ""]
rat = read("rating_params.csv", dtype={"id": str})
if rat is not None:
    out += ["### Rating curves Q = a (h - h0)^b (fitted 2013-2023)\n", md(rat, 3), ""]

# ---- Part A: CV ----
cv = read("tables_cv.csv")
if cv is not None:
    cv = cv.rename(columns={cv.columns[0]: "method"})
    out += ["## Part A: flood water mapping (Sen1Floods11 test chips, water class)\n", md(cv), ""]
seed_files = [REP / "tables_cv.csv"] + sorted(REP.glob("tables_cv_seed*.csv"))
if len(seed_files) > 1:
    unet = pd.DataFrame([pd.read_csv(p, index_col=0).loc["U-Net (ResNet-18)"] for p in seed_files])
    unet.index = ["seed " + (p.stem.replace("tables_cv_seed", "") or "42 (default)") for p in seed_files]
    summ = pd.DataFrame({"mean": unet.mean(), "std": unet.std()}).T
    out += [f"### U-Net spread over {len(seed_files)} training seeds (test chips)\n", md(unet, 3), "", md(summ, 3), ""]
area = read("sumas_area.csv")
if area is not None:
    out += ["### Sumas Prairie flooded area from Sentinel-1 (orbit 13), km2\n",
            "`common` = region seen by every scene (257 km2), comparable across dates. "
            "Flooded = water now and not permanent water.\n", md(area, 2), ""]
av = read("area_vs_level.csv")
if av is not None:
    out += ["### Flooded area vs river level / flow (same day; descriptive, few dates)\n", md(av, 2), ""]

out += ["## Limitations\n",
        "- Weather is one ERA5 point per basin (the gauge), no IVT; AR influence is a rain + warmth proxy.",
        "- 'Future weather' is observed reanalysis (a perfect forecast); real forecasts are less accurate.",
        "- Tree models cannot predict beyond the range seen in training, so record peaks are under-predicted.",
        "- Regulation of the gauges was judged from station names only.",
        "- Some gauges failed or were estimated during the Nov 2021 flood.",
        "- The U-Net is trained on global flood chips; radar confuses flat wet fields and wet snow with water.",
        "- Flooded area vs level rests on 8-9 satellite dates: descriptive, not a hydraulic model.", ""]
(REP / "results.md").write_text("\n".join(out), encoding="utf-8")
print("wrote", REP / "results.md", f"({len(out)} blocks)")
